"""
Dalam sebuah kapal antariksa penelitian bernama Astra Voyager, terdapat sebuah mesin
warp yang menentukan kecepatan perjalanan antarbintang.
Mesin ini memiliki modul daya bernomor urut (1, 2, 3, ...). Setiap modul menghasilkan
jumlah daya tertentu. Para insinyur menemukan pola daya modulnya sebagai berikut:
Basic Rule
W(1) = 2
W(2) = 7
Recursive Rule
Mulai modul ke-3: W(n) = 3·W(n−1) − W(n−2)
Buatlah program menggunakan Dynamic Programming (DP) untuk menghitung daya
modul warp W(n) dari modul 1 sampai modul 10. Gunakan fungsi rekursif dengan
memorizing table bernama warp(n).
"""
# ----------------------------------------
# Dynamic Programming dengan array (list)
# ----------------------------------------
dp = [0] * 11
dp[1] = 2
dp[2] = 7

def warp(n):
    if dp[n] != 0:
        return dp[n]

    dp[n] = 3 * warp(n - 1) - warp(n - 2)
    return dp[n]


# Program utama
for i in range(1, 11):
    print(warp(i))

# ----------------------------------------
#   TANPA dynamic programming
# ----------------------------------------

def warp(n):
    # Base Case
    if n == 1:
        return 2
    if n == 2:
        return 7

    # Recursive Rule
    return 3 * warp(n - 1) - warp(n - 2)


# Program utama
for i in range(1, 11):
    print(warp(i))

"""
Seekor kucing penjelajah memasuki sebuah lorong kristal bawah tanah yang berbentuk
grid 2D kecil. Di dalam lorong tersebut terdapat jalan kristal (yang bisa dilewati) dan
dinding batu (yang tidak bisa ditembus).
Kucing ingin mencapai terowongan keluar yang selalu terletak di kolom paling kiri
(kolom 0).
Ia bisa mulai di posisi mana pun, tetapi harus mencari jalur yang valid untuk kembali ke
pintu keluar itu.
Grid berisi nilai berikut:
1 → jalan kristal yang dapat dilewati
0 → dinding batu
2 → jejak kucing (ditandai saat dikunjungi)

room = [[1,1,0,0],
        [0,1,1,0],
        [1,1,1,0],
        [0,0,1,1]]

Kucing dapat bergerak ke lima arah yakni Kiri, Kanan, Atas, Bawah, Diagonal Kiri-
Atas, Diagonal Kiri-Bawah. Namun, Kucing tidak bisa bergerak diagonal ke kanan,

tetapi boleh maju kanan secara lurus.
"""

def escape(m, y, x):
    rows = len(m)
    cols = len(m[0])

    # 1. Cek batas grid
    if y < 0 or y >= rows or x < 0 or x >= cols:
        return False

    # 2. Hanya boleh melangkah di sel bernilai 1 (jalan)
    if m[y][x] != 1:
        return False

    # 3. Tandai sel yang dikunjungi
    m[y][x] = 2

    # 4. Jika sudah mencapai baris paling atas, selesai (berhasil)
    if y == 0:
        return True

    if escape(m, y - 1, x):      # atas
        return True
    if escape(m, y + 1, x):      # bawah
        return True
    if escape(m, y, x + 1):      # kanan
        return True
    if escape(m, y + 1, x - 1):  # diagonal kiri-bawah
        return True
    if escape(m, y, x - 1):      # kiri
        return True
    if escape(m, y - 1, x - 1):  # diagonal kiri-atas
        return True

    # 6. Jika semua arah buntu, backtrack: kembalikan ke 1
    m[y][x] = 1
    return False


room = [[1,1,0,0],
        [0,1,1,0],
        [1,1,1,0],
        [0,0,1,1]]

